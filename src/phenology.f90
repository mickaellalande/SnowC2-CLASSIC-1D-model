!> \file
!! Calculates the leaf status for CTEM's pfts and leaf litter generated by
!! normal turnover of leaves and cold and drought stress; crop harvest; and
!! for grasses green leaves are converted into brown. Also updates vegetation
!! carbon pools for dcd trees and grasses accounting for nsc reallocation during leafout period.
!!
!> @author V. Arora, J. Melton, A. Asaadi
subroutine phenology (il1, il2, ilg, leapnow, tbar, thice, & ! In
                     thliq, THLW, THFC, ta, ipeatland, & ! In
                     anveg, iday, radl, roottemp, useTracer, & ! In
                     rmatctem, sort, fcancmx, isand, dayl_max, & ! In
                     gleafmas, gleafmas_ns, gleafmas_s, & ! In/Out
                     bleafmas, stemmass, stemmass_ns, stemmass_s, & ! In/Out
                     rootmass, rootmass_ns, rootmass_s, & ! In/Out
                     lfstatus, pandays, colddays_leaffall, colddays_harvest, lfthrs, & ! In/Out
                     tracerGLeafMass, tracerBLeafMass, & ! In/Out
                     re_alloc_s2l, re_alloc_r2l, re_alloc_sr2l, & ! Out
                     gl2bl_grass_cflux, bl2ltr_grass_cflux, & ! Out
                     flhrloss, flhrloss_ns, flhrloss_s,leaflitr, leaflitr_ns, & ! Out
                     leaflitr_s, tracerLeafLitr) ! Out
  !
  !               Canadian Terrestrial Ecosystem Model (CTEM)
  !               Phenology, Leaf Turnover & Mortality Subroutine
  !
  !     12 Apr 2022   - Rewrite to improve logical flow and aid understanding. Readjust after the flhrloss bug
  !     J. Melton       removed, fix merge problem with Ali's NSC code.
  !                     
  !     28 Jun 2017   - Incorporate non-structural and structural carbohydrates
  !     A. Asaadi     
  !
  !     25 Apr 2019   - Incorporate tracer
  !     J. Melton
  !     06  Dec 2018  - Pass ilg back in as an argument + minor reorganization
  !     V. Arora        of arguments
  !
  !     7   Nov 2016  - Allow adaptions due to peatland scheme of Yuanqiao Wu.
  !
  !     14  Jan 2016  - There was a bit of hardwired code for 3 soil layers, that has been
  !                     fixed to allow >3.

  !     17  Jan 2014  - Moved parameters to global file (classicParams.f90)
  !     J. Melton
  !
  !     22  Jul 2013  - Add in module for parameters
  !     J. Melton
  !
  !     24  Sep 2012  - add in checks to prevent calculation of non-present
  !     J. Melton       pfts
  !
  !     15  Apr. 2003 - this subroutine calculates the leaf status
  !     V. Arora        for ctem's pfts and leaf litter generated by
  !                     normal turnover of leaves and cold and drought
  !                     stress. crop harvest is also modelled in this
  !                     subroutine, and for grasses green leaves are
  !                     converted into brown.

  use classicParams,    only : kn, pi, zero, kappa, eta, kappa_peat, eta_peat, &
                               lfespany, lfespany_peat, fracbofg, specsla, ignd, icc, &
                               ican, cdlsrtmx, drlsrtmx, drgta, &
                               colda, lwrthrsh, dayschk, coldlmt, &
                               coldthrs, harvthrs, flhrspan, &
                               thrprcnt, roothrsh, ctempfts, nlat, nmos, &
                               nol2pfts, min_ns2t_s, min_ns2t_r, re_alloc, &
                               classpfts, reindexPFTs, TFREZ
  use generalUtils,     only : findDaylength
  use ctemUtilities,    only : calcSLA

  implicit none

  integer, intent(in) :: ilg                 !< no. of grid cells in latitude circle
  integer, intent(in) :: il1                 !< il1=1
  integer, intent(in) :: il2                 !< il2=ilg
  integer, intent(in) :: iday                !< day of year
  integer, intent(in) :: isand(ilg,ignd)     !<
  logical, intent(in) :: leapnow             !< true if this year is a leap year. Only used if the switch 'leap' is true.
  integer, intent(in) :: useTracer  !< Switch for use of a model tracer. If useTracer is 0 then the tracer code is not used.
                                    !! useTracer = 1 turns on a simple tracer that tracks pools and fluxes. The simple tracer then requires that the tracer values in
                                    !! the init_file and the tracerCO2file are set to meaningful values for the experiment being run.
                                    !! useTracer = 2 means the tracer is 14C and will then call a 14C decay scheme.
                                    !! useTracer = 3 means the tracer is 13C and will then call a 13C fractionation scheme.
  integer, intent(in) :: sort(icc)           !< index for correspondence between 9 pfts and the 12 values in parameters vectors
  integer, intent(in) :: ipeatland(ilg)        !< Peatland flag, non-peatlands are 0.
  real, intent(in) :: ta(ilg)                !< air temperature, k
  real, intent(in) :: tbar(ilg,ignd)         !< soil temperature, k
  real, intent(in) :: thliq(ilg,ignd)        !< liquid soil moisture content in soil layers
  real, intent(in) :: thice(ilg,ignd)        !< frozen  soil moisture content in soil layers
  real, intent(in) :: anveg(ilg,icc)         !< net photosynthesis rate of ctem's pfts, umol co2/m2.s
  real, intent(in) :: roottemp(ilg,icc)      !< root temperature, which is a function of soil temperature of course, k.
  real, intent(in) :: rmatctem(ilg,icc,ignd) !< fraction of roots in each soil layer for each pft
  real, intent(inout) :: stemmass(ilg,icc)   !< stem mass for each of the 9 ctem pfts, \f$kg c/m^2\f$
  real, intent(inout) :: stemmass_ns(ilg,icc)!< non-structural stem mass for each of the ctem pfts, \f$kg c/m^2\f$
  real, intent(in)    :: stemmass_s(ilg,icc) !< structural stem mass for each of the ctem pfts, \f$kg c/m^2\f$
  real, intent(inout) :: rootmass(ilg,icc)   !< root mass for each of the 9 ctem pfts, \f$kg c/m^2\f$
  real, intent(inout) :: rootmass_ns(ilg,icc)!< non-structural root mass for each of the 9 ctem pfts, \f$kg c/m^2\f$
  real, intent(in)    :: rootmass_s(ilg,icc) !< structural root mass for each of the 9 ctem pfts, \f$kg c/m^2\f$
  real, intent(in) :: fcancmx(ilg,icc)       !< max. fractional coverage of ctem's 9 pfts, but this can be modified
                                             !< by land-use change, and competition between pfts
  real, intent(in) :: THFC(ilg,ignd)      !< field capacity soil moisture content both calculated in allocate subroutine
  real, intent(in) :: THLW(ilg,ignd)       !< wilting point soil moisture content
  real, intent(in) :: radl(ilg)              !< latitude in radians
  real, intent(inout) :: gleafmas(ilg,icc)      !< green or live leaf mass in \f$kg c/m^2\f$
  real, intent(inout) :: gleafmas_ns(ilg,icc)   !< non-structural green or live leaf mass in \f$kg c/m^2\f$
  real, intent(inout) :: gleafmas_s(ilg,icc)    !< structural green or live leaf mass in \f$kg c/m^2\f$
  real, intent(inout) :: bleafmas(ilg,icc)      !< brown or dead leaf mass in \f$kg c/m^2\f$
  real, intent(inout) :: tracerGLeafMass(ilg,icc)      !< Tracer mass in the green leaf pool for each of the CTEM pfts, \f$kg c/m^2\f$
  real, intent(inout) :: tracerBLeafMass(ilg,icc)      !< Tracer mass in the brown leaf pool for each of the CTEM pfts, \f$kg c/m^2\f$
  integer, intent(inout) :: pandays(ilg,icc)    !< counter for positive net photosynthesis (an) days for initiating leaf onset
  integer, intent(inout) :: lfstatus(ilg,icc)   !< integer :: indicating leaf status or mode
                                                !< 1 - max. growth or onset, when all npp is allocated to leaves
                                                !< 2 - normal growth, when npp is allocated to leaves, stem, and root
                                                !< 3 - fall for dcd trees/harvest for crops, when allocation to leaves is zero.
                                                !< 4 - no leaves
  real, intent(in) :: dayl_max(ilg)             !< maximum daylength for at each location

  integer, intent(inout) :: colddays_leaffall(ilg)    !< cold days counter for tracking days below a certain temperature threshold
                                                      !< for ndl dcd
  integer, intent(inout) :: colddays_harvest(ilg)     !< cold days counter for tracking days below a certain temperature threshold
                                                      !< for crop pfts.
  real, intent(inout) :: flhrloss(ilg,icc)      !< fall & harvest loss for bdl dcd plants and crops, respectively, \f$kg c/m^2\f$.
  real, intent(inout) :: flhrloss_ns(ilg,icc)   !< non-structural fall & harvest loss for bdl dcd plants and crops, respectively, \f$kg c/m^2\f$.
  real, intent(inout) :: flhrloss_s(ilg,icc)    !< structural fall & harvest loss for bdl dcd plants and crops, respectively, \f$kg c/m^2\f$.
  real, intent(out) :: leaflitr(ilg,icc)      !< leaf litter generated by normal turnover, cold and drought stress,
                                              !< and leaf fall/harvest, \f$kg c/m^2\f$
  real, intent(out) :: leaflitr_ns(ilg,icc)   !< non-structural leaf litter \f$kg c/m^2\f$
  real, intent(out) :: leaflitr_s(ilg,icc)    !< structural leaf litter \f$kg c/m^2\f$
  real, intent(out) :: tracerLeafLitr(ilg,icc)  !< leaf litter generated by normal turnover, cold and drought stress,
                                                !< and leaf fall/harvest, \f$tracer C units/m^2\f$
  real, intent(out) :: re_alloc_sr2l(ilg,icc) !< amount of nsc reallocated from stem and root to leaves during leaf out
  real, intent(out) :: re_alloc_s2l(ilg,icc)  !< amount of nsc reallocated from stem to leaves during leaf out
  real, intent(out) :: re_alloc_r2l(ilg,icc)  !< amount of nsc reallocated from root to leaves during leaf out
  real, intent(out) :: gl2bl_grass_cflux(ilg,icc)  !< carbon flux from gleafmas to bleafmass, to be used in nitrogen cycle
  real, intent(out) :: bl2ltr_grass_cflux(ilg,icc) !< litter carbon flux from bleafmas to litrmass, to be used in nitrogen cycle

  ! local
  real :: daylngth(ilg)          !<
  real :: nrmlloss(ilg,icc)      !< leaf loss due to normal turnover
  real :: nrmlloss_ns(ilg,icc)   !< non-structural leaf loss due to normal turnover
  real :: nrmlloss_s(ilg,icc)    !< structural leaf loss due to normal turnover
  real :: tracerNrmlLoss(ilg,icc)!< Tracer leaf loss due to normal turnover
  real :: betadrgt(ilg,ignd)     !< (1 - drought stress)
  real :: drgtstrs(ilg,icc)      !< drought stress term
  real :: drgtlsrt(ilg,icc)      !< drought loss rate
  real :: drgtloss(ilg,icc)      !< leaf loss due to drought stress
  real :: drgtloss_ns(ilg,icc)   !< non-structural leaf loss due to drought stress
  real :: drgtloss_s(ilg,icc)    !< structural leaf loss due to drought stress
  real :: tracerDrgtLoss(ilg,icc)!< Tracer leaf loss due to drought stress
  real :: coldloss(ilg,icc)      !< leaf loss due to cold stress
  real :: coldloss_ns(ilg,icc)   !< non-structural leaf loss due to cold stress
  real :: coldloss_s(ilg,icc)    !< structural leaf loss due to cold stress
  real :: tracerColdLoss(ilg,icc)!< Tracer leaf loss due to cold stress
  real :: coldstrs(ilg,icc)      !< cold stress term
  real :: coldlsrt(ilg,icc)      !< cold loss rate
  real :: tracerFlHrLoss(ilg,icc)!< Tracer fall & harvest loss for bdl dcd plants and crops, respectively, \f$kg c/m^2\f$.
  real :: lfthrs(ilg,icc)        !< threshold lai for finding leaf status
  character(8) :: pftkind
  integer :: i, j, k, m, n
  real :: sla(icc)               !< specific leaf area
  real :: ailcg(ilg,icc)         !< green lai
  real :: ailcb(ilg,icc)         !< brown lai
  logical :: reallocateWoody(ilg,icc) !< check whether to permit reallocation of C for trees/shrubs
  logical :: reallocateHerb(ilg,icc)  !< check whether to permit reallocation of C for grasses/sedges
  logical :: befSummerSolstice(ilg)      !< Check if this location is before summer solstice.
  real :: frac                   !< temp var.
  real :: lastDOY                !< last day of the year 
  real :: lwrtemp                !< temp var. to set two different lwrthrsh before and after summer solstice.
  real :: stemns2t, rootns2t     !< temp ratios for nonstructural to total pools
  real :: ns_s2sr,ns_r2sr        !< temp ratios for nonstructural pools: stem/(stem+root) & root/(stem+root)
  
  ! Initialize required arrays to zero
  betadrgt = 0.0
  sla = 0.0
  ailcg = 0.0
  ailcb = 0.0
  leaflitr = 0.0
  leaflitr_ns = 0.0
  leaflitr_s = 0.0
  tracerLeafLitr = 0.
  nrmlloss = 0.0
  nrmlloss_ns = 0.0
  nrmlloss_s = 0.0
  drgtstrs = 0.0
  drgtlsrt = 0.0
  drgtloss = 0.0
  drgtloss_ns = 0.0
  drgtloss_s = 0.0
  coldstrs = 0.0
  coldlsrt = 0.0
  coldloss = 0.0
  coldloss_ns = 0.0
  coldloss_s = 0.0
  lfthrs = 0.0
  re_alloc_sr2l = 0.0
  re_alloc_s2l = 0.0
  re_alloc_r2l = 0.0
  gl2bl_grass_cflux = 0.0
  bl2ltr_grass_cflux = 0.0
  tracerFlHrLoss = 0.
  tracerNrmlLoss = 0.
  tracerDrgtLoss = 0.
  tracerColdLoss = 0.
  
   ! initialize reallocation flag to false for all PFTs
  reallocateWoody = .false.
  reallocateHerb = .false.

  ! Initialization ends

  !------------------------------------------------------------------
  !> Set the number of days in this year.
  if (.not. leapnow) then
    lastDOY = 365.
  else 
    lastDOY = 366.
  end if 
  
  !> First check some climate indices to see whether limits have been passed
  !> find day length using day of year and latitude. this is to be used for
  !! initiating leaf offset for broad leaf dcd trees.
  do i = il1,il2
    daylngth(i) = findDaylength(real(iday),radl(i))

    !! Similar to the way we count number of days when an is positive, we
    !! find number of days when temperature is below -5 C. We need this to
    !! determine if we go into "leaf fall" mode for needle leaf dcd trees.
    if (ta(i) < (coldthrs(1) + TFREZ)) then
      colddays_leaffall(i) = colddays_leaffall(i) + 1
      if (colddays_leaffall(i) > coldlmt(1)) then
        colddays_leaffall(i) = coldlmt(1)
      end if
    else
      colddays_leaffall(i) = 0
    end if

    !! Also estimate number of days below 8 C. We use these days to decide
    !! if its cold enough to harvest crops.
    if (ta(i) < (coldthrs(2) + TFREZ)) then
      colddays_harvest(i) = colddays_harvest(i) + 1
      if (colddays_harvest(i) > coldlmt(2)) then
        colddays_harvest(i) = coldlmt(2)
      end if
    else
      colddays_harvest(i) = 0
    end if

    ! Determine for each tile if we are before (true), or after (false) summer solstice.
    if ((radl(i) > 0. .and. iday < 172 ) .or. &
        (radl(i) < 0. .and. (iday >= 172 .and. iday < 356))) then 
      befSummerSolstice(i) = .true.
    else 
      befSummerSolstice(i) = .false.
    end if 

  end do 

  !> Next calculate some vegetation state basics (LAI, threshold LAI)

  !> Convert green leaf mass into leaf area index using specific leaf
  !! area \f$(sla, m^2 /kg c)\f$ estimated using leaf life span. see applyAllometry
  !! subroutine for more details.
  do j = 1,icc
    n = sort(j)
    do i = il1,il2
      sla(j) = calcSLA(ipeatland(i),sort(j))  !FLAG - why do this every time step when it is based upon parameters that are set at run start? JM 2022
      if (fcancmx(i,j) > 0.0) then
        ailcg(i,j) = sla(j) * gleafmas(i,j)
        ailcb(i,j) = sla(j) * bleafmas(i,j) * fracbofg

        !> Also find threshold LAI as a function of stem + root biomass
        !! which is used to determine leaf status
        if (ipeatland(i) /= 1 .and. ipeatland(i) /= 2) then !uplands
          lfthrs(i,j) = ((stemmass_s(i,j) + rootmass_s(i,j)) &
                          / eta(n)) ** (1.0 / kappa(n))
        else ! peatlands 
          lfthrs(i,j) = ((stemmass_s(i,j) + rootmass_s(i,j)) &
                          / eta_peat(n)) ** (1.0 / kappa_peat(n))
        end if 
        lfthrs(i,j) = (thrprcnt(n) / 100.0) * sla(j) * lfthrs(i,j)

        !> Check that we have a lfstatus. It is possible to enter phenology with a leaf status
        !! of 0. This could be due to land use change or competition bringing a new PFT into
        !! a tile where it wasn't previously. If so, then follow the logic below to assign a value
        !! If the lfstatus is 
        if (lfstatus(i,j) <= 0) then
          if (ailcg(i,j) <= zero) then
            lfstatus(i,j) = 4  ! no leaves
          else if (ailcg(i,j) > lfthrs(i,j)) then
            lfstatus(i,j) = 2  ! normal growth
          else
            lfstatus(i,j) = 4  ! treat this as no leaves so that we start growing
          end if                                 
        else if (lfstatus(i,j) < 0 .or. lfstatus(i,j) > 4) then 
          ! Something has really gone wrong, kill the run and notify.
          print * ,'no valid value given for lfstatus in phenology ',i,j,lfstatus(i,j)
          call errorHandler('phenology', 0)          
        end if 

        ! Add one to pandays(i,j) if daily An is positive, otherwise set it to zero.
        if (anveg(i,j) > zero) then
          pandays(i,j) = pandays(i,j) + 1
          if (pandays(i,j) > dayschk(n)) then
            pandays(i,j) = dayschk(n)
          end if
        else
          pandays(i,j) = 0
        end if      

      end if ! fcancmx
    end do ! loop 180
  end do ! loop 170

  !> Now we start to check on whether the leaf status should be changing by going through each
  !! PFT that is present. Note that the code below only changes the lfstatus should there be a 
  !! reason to update it. Otherwise the lfstatus value at the start of the subroutine are simply retained.
  !! Reminder of the lfstatus values:
  !< 1 - Maximum growth or leaf onset. A.ll NPP is allocated to leaves
  !< 2 - Normal growth. NPP is allocated to leaves, stems, and roots.
  !< 3 - Senesence for deciduous PFTs/harvest for crops. Allocation to leaves is zero.
  !< 4 - No leaves
  do i =  il1,il2
    do j = 1,icc
      n = sort(j)
      if (fcancmx(i,j) > 0.0) then
        pftkind = ctempfts(j)
        select case (pftkind)

        case ('NdlEvgTr') ! Needleleaf Evergreen Tree ==========================

          if (lfstatus(i,j) == 1) then ! max growth

            if (ailcg(i,j) <= zero) then ! no leaves
              lfstatus(i,j) = 4          ! so switch to "no leaves" mode
              pandays(i,j) = 0
            else if (ailcg(i,j) >= lfthrs(i,j)) then
              lfstatus(i,j) = 2 ! switch to "normal growth" mode
            end if  

          else if (lfstatus(i,j) == 2) then ! normal growth

            if (ailcg(i,j) < lfthrs(i,j) .and. ailcg(i,j) > zero) then
              lfstatus(i,j) = 1         ! go back to "max. growth" mode              
            else if (ailcg(i,j) <= zero) then
              lfstatus(i,j) = 4         ! switch to "no leaves" mode
              pandays(i,j) = 0
            end if

          !Evergreens do not enter (lfstatus(i,j) == 3)

          else if (lfstatus(i,j) == 4) then ! no leaves

            ! Start puttting out leaves if conditions have been good. 
            if (pandays(i,j) >= dayschk(n)) then
              lfstatus(i,j) = 1        ! switch to "max. growth" mode
            end if

          else ! bad lfstatus value
            print * ,'Bad NdlEvgTr lftstatus in phenology ',pftkind
            call errorHandler('phenology', - 1)
          end if

        case ('NdlDcdTr') ! Needleleaf Deciduous Tree =======================

          if (lfstatus(i,j) == 1) then ! max growth

            if (ailcg(i,j) <= zero) then ! no leaves
              lfstatus(i,j) = 4         ! switch to "no leaves" mode
              pandays(i,j) = 0
            else ! leaves are present
              !> For dcd trees we also need to be able to go into "leaf fall" mode (lfstatus = 3)
              !! directly from "max. growth" mode. So check if conditions are bad
              if ((ailcg(i,j) > zero .and. colddays_leaffall(i) >= coldlmt(1)) & 
                  .or. roottemp(i,j) < (roothrsh + TFREZ)) then
                lfstatus(i,j) = 3
                flhrloss(i,j) = gleafmas(i,j) * (1.0 / flhrspan(2))
                flhrloss_ns(i,j) = gleafmas_ns(i,j) * (1.0 / flhrspan(2))
                flhrloss_s(i,j)  = gleafmas_s(i,j)  * (1.0 / flhrspan(2))
                if (useTracer > 0) tracerFlHrLoss(i,j) = tracerGLeafMass(i,j) * (1.0 / flhrspan(2))
              else ! conditions are good
                if (ailcg(i,j) < lfthrs(i,j)) then ! check if LAI is below the threshold (lfthrs)
                  if (befSummerSolstice(i)) then
                    ! Set reallocation to true for later calculations.
                    reallocateWoody(i,j) = .true.
                  end if 
                else if (ailcg(i,j) >= lfthrs(i,j)) then
                  lfstatus(i,j) = 2 ! switch to "normal growth" mode
                end if
              end if 
            end if 

          else if (lfstatus(i,j) == 2) then ! normal growth

            if ((ailcg(i,j) > zero .and. colddays_leaffall(i) >= coldlmt(1)) & 
                  .or. roottemp(i,j) < (roothrsh + TFREZ)) then
              lfstatus(i,j) = 3         ! go into "leaf fall" mode
              flhrloss(i,j) = gleafmas(i,j) * (1.0 / flhrspan(2))
              flhrloss_ns(i,j) = gleafmas_ns(i,j) * (1.0 / flhrspan(2))
              flhrloss_s(i,j)  = gleafmas_s(i,j)  * (1.0 / flhrspan(2))
              if (useTracer > 0) tracerFlHrLoss(i,j) = tracerGLeafMass(i,j) * (1.0 / flhrspan(2))
            else if (ailcg(i,j) > zero .and. ailcg(i,j) < lfthrs(i,j)) then
              lfstatus(i,j) = 1         ! switch to "max. growth" mode
            else if (ailcg(i,j) <= zero) then
              lfstatus(i,j) = 4         ! switch to "no leaves" mode
              pandays(i,j) = 0
            end if

          else if (lfstatus(i,j) == 3) then ! leaf fall 

            if (ailcg(i,j) <= 0.01) then ! leaves are gone
              lfstatus(i,j) = 4            ! go into "no leaves" mode, flhrloss later.
              pandays(i,j) = 0
              ! flhrloss(i,j) = 0.0  ! reset to 0.
              ! flhrloss_ns(i,j) = 0.0
              ! flhrloss_s(i,j)  = 0.0
              ! if (useTracer > 0) tracerFlHrLoss(i,j) = 0.
            else ! still have leaves
              ! Check if conditions have improved enough to try resuming growth
              if (pandays(i,j) >= dayschk(j) .and. ta(i) > (coldthrs(1) + TFREZ)) then
                ! reset the flhrloss
                ! flhrloss(i,j) = 0.0  ! reset to 0.
                ! flhrloss_ns(i,j) = 0.0
                ! flhrloss_s(i,j)  = 0.0
                if (ailcg(i,j) < lfthrs(i,j)) then
                  lfstatus(i,j) = 1      ! go into "max. growth" mode
                else
                  lfstatus(i,j) = 2      ! go into "normal growth" mode
                end if
              end if
            end if

          else if (lfstatus(i,j) == 4) then ! no leaves

            ! ! If a new PFT is ever started with lfstatus of 4, this makes sure 
            ! ! these are correctly set.
            ! flhrloss(i,j) = 0.0  ! reset to 0.
            ! flhrloss_ns(i,j) = 0.0
            ! flhrloss_s(i,j)  = 0.0
            ! if (useTracer > 0) tracerFlHrLoss(i,j) = 0.

            if (pandays(i,j) >= dayschk(n) .and. ta(i) > (coldthrs(1) + TFREZ)) then
              ! Ok to switch to "max. growth" mode
              lfstatus(i,j) = 1  
            end if 

          else ! bad lfstatus value
            print * ,'Bad NdlDcdTr lftstatus in phenology ',pftkind
            call errorHandler('phenology', - 1)
          end if 

        case ('BdlEvgTr') ! Broadleaf Evergreen Tree =========================

          if (lfstatus(i,j) == 1) then ! max growth

            if (ailcg(i,j) <= zero) then ! no leaves
              lfstatus(i,j) = 4         ! switch to "no leaves" mode
              pandays(i,j) = 0
            else if (ailcg(i,j) >= lfthrs(i,j)) then
              lfstatus(i,j) = 2 ! switch to "normal growth" mode
            end if       

          else if (lfstatus(i,j) == 2) then ! normal growth

            if (ailcg(i,j) < lfthrs(i,j) .and. ailcg(i,j) > zero) then
              lfstatus(i,j) = 1         ! go back to "max. growth" mode
            else if (ailcg(i,j) <= zero) then
              lfstatus(i,j) = 4         ! switch to "no leaves" mode
              pandays(i,j) = 0
            end if

          !Evergreens do not enter (lfstatus(i,j) == 3) 

          else if (lfstatus(i,j) == 4) then ! no leaves
            ! Start puttting out leaves if conditions have been good. 
            if (pandays(i,j) >= dayschk(n)) then
              lfstatus(i,j) = 1        ! switch to "max. growth" mode
            end if

          else ! bad lfstatus value
            print * ,'Bad BdlEvgTr lftstatus in phenology ',pftkind
            call errorHandler('phenology', - 1)
          end if

