              pandays(i,j) = 0
              ! flhrloss(i,j) = 0.0
              ! flhrloss_ns(i,j) = 0.0
              ! flhrloss_s(i,j)  = 0.0
              ! if (useTracer > 0) tracerFlHrLoss(i,j) = 0.
